import assert from 'node:assert/strict';
import { createRequire } from 'node:module';
const require = createRequire(new URL('../appwrite/functions/presences-backend/package.json', import.meta.url));
const { PDFDocument } = require('pdf-lib');
const { bulkIdCards } = await import('../appwrite/functions/presences-backend/src/bulk-id-cards.js');
const admin = { $id: 'admin', labels: ['admin'] };
const pdf = await PDFDocument.create(); pdf.addPage(); pdf.addPage();
const fileData = Buffer.from(await pdf.save()).toString('base64');
process.env.GEMINI_API_KEY = 'test-key';
let calls = 0;
const mockGemini = async (_url, request) => {
  calls++;
  assert.equal(request.headers['x-goog-api-key'], 'test-key');
  const page = await PDFDocument.load(Buffer.from(JSON.parse(request.body).contents[0].parts[1].inlineData.data, 'base64'));
  assert.equal(page.getPageCount(), 1);
  return { ok: true, json: async () => ({ candidates: [{ content: { parts: [{ text: JSON.stringify({ card_count: 8, cards: Array.from({ length: 8 }, (_, index) => ({ name: index === 7 ? '' : `Student ${index}`, admission_number: `00${index}`, class: '11 A' })) }) }] } }] }) };
};
await assert.rejects(bulkIdCards({ action: 'idcards.extract', fileData }, { labels: ['teacher'] }, {}, 'db', mockGemini), { status: 403 });
const first = await bulkIdCards({ action: 'idcards.extract', fileData, page: 1 }, admin, {}, 'db', mockGemini);
const last = await bulkIdCards({ action: 'idcards.extract', fileData, page: 2 }, admin, {}, 'db', mockGemini);
assert.equal(first.cards.length + last.cards.length, 16); assert.equal(calls, 2);
assert.equal(first.nextPage, 2); assert.equal(last.nextPage, null);
assert.equal(first.cards[0].admission_number, '000'); assert.equal(first.cards[0].class, '11'); assert.equal(first.cards[0].section, 'A');
assert.equal(first.cards[7].needs_review, true);
await assert.rejects(bulkIdCards({ action: 'idcards.extract', fileData: 'aaaa' }, admin, {}, 'db', mockGemini), { status: 400 });
const badCoverage = async () => ({ ok: true, json: async () => ({ candidates: [{ content: { parts: [{ text: '{"card_count":8,"cards":[]}' }] } }] }) });
await assert.rejects(bulkIdCards({ action: 'idcards.extract', fileData }, admin, {}, 'db', badCoverage), /coverage/);
let writes = 0, stored;
const db = { listDocuments: async () => ({ documents: [] }), createDocument: async (_db, _table, _id, data) => { writes++; stored = data; } };
const student = { name: 'Test Student', admission_number: '00123', father_name: 'Parent', parent_phone: '9910014616', pen_number: '00123456789', blood_group: 'A-' };
await assert.rejects(bulkIdCards({ action: 'idcards.save', students: [student, student] }, admin, db, 'db'), /Duplicate/);
assert.equal(writes, 0);
const saved = await bulkIdCards({ action: 'idcards.save', students: [student] }, admin, db, 'db');
assert.deepEqual(saved.saved, ['00123']); assert.equal(saved.success, true);
assert.equal(stored.parent_phone, '+919910014616'); assert.equal(JSON.parse(stored.metadata).pen_number, '00123456789');
db.createDocument = async () => { throw new Error('Database unavailable'); };
const failed = await bulkIdCards({ action: 'idcards.save', students: [student] }, admin, db, 'db');
assert.equal(failed.success, false); assert.equal(failed.saved.length, 0); assert.equal(failed.failed.length, 1);
db.listDocuments = async () => ({ documents: [{ $id: 'staff', role: 'teacher' }] });
assert.equal((await bulkIdCards({ action: 'idcards.save', students: [student], approveUpdates: true }, admin, db, 'db')).failed.length, 1);
db.listDocuments = async () => ({ documents: [{ $id: 'existing', role: 'student', class: '11', section: 'B', address: 'Verified address', metadata: '{"pen_number":"verified-pen"}' }] });
db.updateDocument = async (_db, _table, _id, data) => { stored = data; };
assert.equal((await bulkIdCards({ action: 'idcards.save', students: [{ name: 'Updated Name', admission_number: '00123' }], approveUpdates: true }, admin, db, 'db')).success, true);
assert.equal(Object.hasOwn(stored, 'address'), false);
assert.equal(stored.category, '11-B');
assert.equal(JSON.parse(stored.metadata).pen_number, 'verified-pen');
delete process.env.GEMINI_API_KEY;
await assert.rejects(bulkIdCards({ action: 'idcards.extract', fileData }, admin, {}, 'db', mockGemini), { status: 503 });
console.log('PASS: backend PDF page splitting, 16 cards, incomplete-card retention, coverage checks, staff authorization, leading-zero IDs, duplicate validation before writes, metadata persistence and truthful partial-save failures.');
